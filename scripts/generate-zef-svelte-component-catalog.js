#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const toml = require('@iarna/toml');

const extensionRoot = path.resolve(__dirname, '..');
const componentsDirectory = path.join(extensionRoot, 'zef-svelte-components');
const outputPath = path.join(extensionRoot, 'src', 'generated', 'zefSvelteComponentCatalog.ts');

function findSvelteFiles(directory) {
    if (!fs.existsSync(directory)) return [];
    return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
        const entryPath = path.join(directory, entry.name);
        if (entry.isDirectory()) return findSvelteFiles(entryPath);
        return entry.isFile() && entry.name.endsWith('.svelte') ? [entryPath] : [];
    });
}

function parseHeader(source, filePath) {
    const match = source.match(/^\s*<!--\s*\+\+\+\s*\n([\s\S]*?)\n\+\+\+\s*-->/);
    if (!match) throw new Error(`${filePath}: missing TOML component header`);

    let header;
    try {
        header = toml.parse(match[1]);
    } catch (error) {
        throw new Error(`${filePath}: invalid TOML component header: ${error.message}`);
    }

    if (typeof header.this !== 'string' || !header.this.startsWith('ET.SvelteComponent(')) {
        throw new Error(`${filePath}: header.this must identify an ET.SvelteComponent`);
    }

    const dispatchedOn = typeof header.dispatched_on === 'string'
        ? [header.dispatched_on]
        : Array.isArray(header.dispatched_on) ? header.dispatched_on : [];
    if (dispatchedOn.length === 0 || dispatchedOn.some(type => typeof type !== 'string' || !/^(ET\.[A-Za-z][A-Za-z0-9_]*|Graph)$/.test(type))) {
        throw new Error(`${filePath}: dispatched_on must be an ET type or supported native value type`);
    }

    return { componentId: header.this, dispatchedOn };
}

const components = findSvelteFiles(componentsDirectory)
    .sort()
    .map(filePath => {
        const relativePath = path.relative(extensionRoot, filePath).split(path.sep).join('/');
        return { ...parseHeader(fs.readFileSync(filePath, 'utf8'), relativePath), relativePath };
    });

const owners = new Map();
for (const component of components) {
    for (const entityType of component.dispatchedOn) {
        const existing = owners.get(entityType);
        if (existing) throw new Error(`${entityType} is dispatched by both ${existing} and ${component.relativePath}`);
        owners.set(entityType, component.relativePath);
    }
}

const output = `// Generated by scripts/generate-zef-svelte-component-catalog.js. Do not edit.\n\nexport interface RegisteredZefSvelteComponent {\n    componentId: string;\n    dispatchedOn: readonly string[];\n    relativePath: string;\n}\n\nexport const registeredZefSvelteComponents: readonly RegisteredZefSvelteComponent[] = ${JSON.stringify(components, null, 4)};\n`;
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(`Generated Zef Svelte component catalogue with ${components.length} component(s).`);
